ALTER TABLE agent_tool_calls
  ADD COLUMN outcome VARCHAR(16) NOT NULL DEFAULT 'COMPLETED';

ALTER TABLE agent_tool_calls
  ADD CONSTRAINT agent_tool_call_outcome_check
  CHECK (outcome IN ('COMPLETED', 'PENDING'));

CREATE TABLE agent_tool_result_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id VARCHAR(36) NOT NULL,
  turn_index INTEGER NOT NULL,
  tool_name VARCHAR(64) NOT NULL,
  result_id VARCHAR(500) NOT NULL,
  result_summary VARCHAR(500) NOT NULL,
  result_output TEXT NOT NULL,
  response_content TEXT,
  decision_reason VARCHAR(500),
  status VARCHAR(16) NOT NULL,
  created_at TIMESTAMP(6) NOT NULL,
  completed_at TIMESTAMP(6),
  CONSTRAINT uk_agent_tool_result_event UNIQUE (tool_name, result_id),
  CONSTRAINT fk_agent_tool_result_event_turn
    FOREIGN KEY (session_id, turn_index)
    REFERENCES agent_turns(session_id, turn_index) ON DELETE CASCADE,
  CONSTRAINT agent_tool_result_event_status_check
    CHECK (status IN ('RECEIVED', 'COMPLETED'))
);

CREATE INDEX idx_agent_tool_result_events_session_created
  ON agent_tool_result_events (session_id, created_at);
